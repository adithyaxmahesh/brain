export const agentById = Object.fromEntries(agents.map((a) => [a.id, a])) as Record<string, Agent>;
export const actionById = Object.fromEntries(actions.map((a) => [a.id, a])) as Record<string, Action>;

export function pendingActions(companyId: string | null = null): Action[] {
  return actions
    .filter((a) => a.status === 'pending-approval')
    .filter((a) => !companyId || a.company_id === companyId || a.company_id === null)
    .sort((a, b) => b.level - a.level || a.requested.localeCompare(b.requested));
}

export function actionsForAgent(agentId: string): Action[] {
  return actions.filter((a) => a.agent_id === agentId);
}

